import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const port = 5198;
const server = spawn(process.execPath, ['scripts/serve.mjs'], { env: { ...process.env, PORT: String(port) }, stdio: 'pipe', windowsHide: true });
let browser;
try {
  await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); server.once('exit', code => reject(new Error(`Preview exited: ${code}`))); });
  browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => { Math.random = () => .9; });
  await page.goto(`http://127.0.0.1:${port}`, { waitUntil: 'networkidle' });
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
  assert.equal(await page.locator('[data-zone]').count(), 5);
  await page.click('[data-difficulty="easy"]');
  await page.click('#action-button');
  await page.waitForFunction(() => document.getElementById('simulation-status').textContent.includes('예매가 열렸어요'));
  await page.click('[data-zone="D"]');
  await page.click('[data-seat="D-8-11"]');
  await page.click('#action-button');
  await page.waitForSelector('dialog[open]');
  assert.equal(await page.locator('#result-title').textContent(), '내 자리를 찾았어요!');
  assert.match(await page.locator('#result-description').textContent(), /D구역 8열 11번/);
  await page.click('#retry');
  await page.selectOption('#quantity', '2');
  await page.click('#action-button');
  await page.waitForFunction(() => document.getElementById('simulation-status').textContent.includes('예매가 열렸어요'));
  await page.click('[data-zone="D"]');
  await page.click('[data-seat="D-8-9"]');
  await page.click('[data-seat="D-8-11"]');
  assert.equal(await page.locator('#action-button').isDisabled(), true);
  await page.click('[data-seat="D-8-9"]');
  await page.click('[data-seat="D-8-12"]');
  await page.click('#action-button');
  await page.waitForSelector('dialog[open]');
  assert.match(await page.locator('#result-description').textContent(), /11번.*12번/);
  await page.click('#close-result');
  await page.reload();
  await page.click('.nav-item[data-view="history"]');
  assert.equal(await page.locator('.history-row').count(), 2);
  await page.click('.nav-item[data-view="practice"]');
  await page.click('[data-difficulty="normal"]');
  await page.click('#action-button');
  await page.waitForFunction(() => document.getElementById('simulation-status').textContent.includes('예매가 열렸어요'));
  await page.click('[data-zone="D"]');
  await page.click('[data-seat="D-8-11"]');
  await page.evaluate(() => { Math.random = () => .01; });
  await page.click('#action-button');
  await page.waitForFunction(() => document.getElementById('simulation-status').textContent.includes('아쉽지만'));
  assert.equal(await page.locator('[data-seat="D-8-11"]').isDisabled(), true);
  assert.equal(await page.locator('#action-button').isDisabled(), true);
  await page.screenshot({ path: 'artifacts/seat-selection.png', fullPage: true });
  await page.click('#cancel-practice');
  assert.equal(await page.locator('#quantity').isEnabled(), true);
  await page.click('#action-button');
  await page.click('#cancel-practice');
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('#action-button').textContent(), '연습 시작 ↗');
  assert.equal(await page.locator('#timer').textContent(), '00:00.0');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(`http://127.0.0.1:${port}`, { waitUntil: 'networkidle' });
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
  await mobile.click('[data-zone="A"]');
  assert.equal(await mobile.locator('[data-seat]').count(), 96);
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  const denied = await browser.newPage();
  await denied.addInitScript(() => { Storage.prototype.getItem = () => { throw new Error('blocked'); }; Storage.prototype.setItem = () => { throw new Error('blocked'); }; });
  await denied.goto(`http://127.0.0.1:${port}`);
  assert.equal(await denied.locator('[data-zone]').count(), 5);
  for (const path of ['/.git/config', '/package.json', '/app.js/../../.git/config']) assert.equal((await fetch(`http://127.0.0.1:${port}${path}`)).status, 404);
  console.log('PASS: single seat, adjacent pair, non-adjacent rejection, competing confirmation, persistent history, mobile layout, blocked storage, private file isolation');
} finally {
  await browser?.close(); server.kill();
}
